#!/usr/bin/env python3
"""
make_controllers_yaml.py -- writes config/controllers.yaml from the ros2_control xacro.

The GPIO controller must list every gpio and interface by name.  Typing that list by hand
would drift from the xacro, so it is generated:   python3 scripts/make_controllers_yaml.py
"""
import os, xacro
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
URDF = os.path.join(HERE, "..", "..", "payload_hardware", "config", "payload_description.urdf")
xml = xacro.process_file(os.path.join(HERE, "..", "urdf", "payload.urdf.xacro"),
                         mappings={"description_file": URDF, "hardware": "can"}).toxml()
rc = ET.fromstring(xml).find("ros2_control")

gpios = []
for g in rc.findall("gpio"):
    gpios.append((g.get("name"),
                  [c.get("name") for c in g.findall("command_interface")],
                  [s.get("name") for s in g.findall("state_interface")]))

out = ["# GENERATED by scripts/make_controllers_yaml.py from urdf/payload.ros2_control.xacro. Do not edit by hand.",
       "controller_manager:",
       "  ros__parameters:",
       "    update_rate: 50          # Hz. Telemetry arrives at 20 Hz; measure the real loop before raising this.",
       "",
       "    joint_state_broadcaster:",
       "      type: joint_state_broadcaster/JointStateBroadcaster",
       "    main_position_controller:",
       "      type: position_controllers/JointGroupPositionController",
       "    drill_velocity_controller:",
       "      type: velocity_controllers/JointGroupVelocityController",
       "    payload_io_controller:",
       "      type: gpio_controllers/GpioCommandController",
       "",
       "joint_state_broadcaster:",
       "  ros__parameters:",
       "    joints: [vps_screw_rotation, drill_lift_screw_rotation, carousel_rotation, soil_sampler_rotation, drill_tool_rotation]",
       "",
       "main_position_controller:",
       "  ros__parameters:",
       "    joints: [vps_screw_rotation, drill_lift_screw_rotation, carousel_rotation, soil_sampler_rotation]",
       "",
       "drill_velocity_controller:",
       "  ros__parameters:",
       "    joints: [drill_tool_rotation]",
       "",
       "# One controller carries every non-joint device: commands in, telemetry out (published on its state topic).",
       "payload_io_controller:",
       "  ros__parameters:",
       "    gpios: [" + ", ".join(n for n, _, _ in gpios) + "]",
       "    command_interfaces:"]
for n, c, _ in gpios:
    if c:
        out.append(f"      {n}:")
        out.append(f"        interfaces: [{', '.join(c)}]")
out.append("    state_interfaces:")
for n, _, s in gpios:
    if s:
        out.append(f"      {n}:")
        out.append(f"        interfaces: [{', '.join(s)}]")
open(os.path.join(HERE, "..", "config", "controllers.yaml"), "w").write("\n".join(out) + "\n")
print("wrote config/controllers.yaml with", len(gpios), "gpios")
